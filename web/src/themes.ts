import type { ITheme } from '@xterm/xterm';

const COMPLETE_THEME_KEYS = [
  'background', 'foreground', 'cursor', 'cursorAccent', 'selectionBackground',
  'black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white',
  'brightBlack', 'brightRed', 'brightGreen', 'brightYellow', 'brightBlue',
  'brightMagenta', 'brightCyan', 'brightWhite',
] as const;

type CompleteThemeKey = (typeof COMPLETE_THEME_KEYS)[number];
export type CompleteXtermTheme = ITheme & Required<Pick<ITheme, CompleteThemeKey>>;

// Standard terminal color schemes. All are battle-tested palettes
// designed (or refined over years of use) to work well in both foreground
// and background roles — which is what makes LS_COLORS combos like
// blue-on-green readable.
//
// Adding a new theme: append an entry. Keep the name stable across
// versions — users' saved selections are keyed on `name`.

export interface TerminalTheme {
  name: string;
  description: string;
  // Every visual role is required so a scheme can never update ANSI ink while
  // accidentally inheriting the previous scheme's canvas/background roles.
  xterm: CompleteXtermTheme;
}

export const TERMINAL_BACKGROUND_CSS_PROPERTY = '--terminal-background';

type ThemeableTerminal = { options: { theme?: ITheme } };

/** Apply the complete xterm palette and its surrounding surface in one turn. */
export function applyTerminalTheme(
  terminal: ThemeableTerminal,
  host: HTMLElement,
  theme: TerminalTheme,
): void {
  // A fresh, complete object triggers xterm's renderer refresh and prevents
  // later mutation of the shared palette catalogue.
  const palette: CompleteXtermTheme = { ...theme.xterm };
  host.style.setProperty(TERMINAL_BACKGROUND_CSS_PROPERTY, palette.background);
  terminal.options.theme = palette;
}


package main

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const installIDBytes = 16

// legacyInstallIDMinLen is the acceptance rule of the pre-ownership reader:
// any persisted value of at least this many characters was used verbatim as
// the updater cohort key.
const legacyInstallIDMinLen = 16

// loadOrCreateInstallID returns the durable, per-install identity used for
// browser-window ownership. It deliberately fails closed: returning an identity
// which was not durably persisted would make a native browser window impossible
// to identify after the daemon restarts. The updater cohort key is derived from
// the same file by installCohortID, which never fails closed.
func loadOrCreateInstallID(dataDir string) (string, error) {
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return "", fmt.Errorf("create install identity directory: %w", err)
	}
	lock, err := acquireBrowserWindowLock(context.Background(), filepath.Join(dataDir, "install-id.lock"), false)
	if err != nil {
		return "", fmt.Errorf("lock install identity: %w", err)
	}
	defer releaseBrowserWindowLock(lock)

	path := filepath.Join(dataDir, "install-id")
	raw, err := os.ReadFile(path)
	switch {
	case err == nil && len(strings.TrimSpace(string(raw))) >= legacyInstallIDMinLen:
		return durableInstallIDFromFile(raw)
	case err == nil:
		// Empty or short (e.g. truncated) values were never usable by either
		// reader: the pre-ownership reader regenerated them, so neither an
		// updater cohort nor a browser ownership lease can be bound to one.
		// Repair the file under the lock rather than failing closed forever.
	case !errors.Is(err, os.ErrNotExist):
		return "", fmt.Errorf("read durable install identity: %w", err)
	}

	buf := make([]byte, installIDBytes)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("generate durable install identity: %w", err)
	}
	id := hex.EncodeToString(buf)
	if err := writeFileAtomicSynced(path, []byte(id+"\n"), 0o600); err != nil {
		return "", fmt.Errorf("persist durable install identity: %w", err)
	}
	return id, nil
}

// durableInstallIDFromFile maps persisted install-id bytes to the ownership
// identity. Canonical values are used verbatim. Values the pre-ownership reader
// accepted (at least 16 characters, e.g. hand-provisioned, uppercase or
// BOM-prefixed files) are grandfathered without rewriting the file: ownership
// uses a canonical digest of that durable value, which is stable across
// restarts, while installCohortID keeps the raw value so the updater cohort
// does not move. Shorter or empty values are regenerated by
// loadOrCreateInstallID before reaching here; they are rejected defensively.
func durableInstallIDFromFile(raw []byte) (string, error) {
	id := strings.TrimSpace(string(raw))
	err := validateInstallID(id)
	if err == nil {
		return id, nil
	}
	if len(id) >= legacyInstallIDMinLen {
		sum := sha256.Sum256([]byte("soluterminal-legacy-install-id\x00" + id))
		return hex.EncodeToString(sum[:installIDBytes]), nil
	}
	return "", fmt.Errorf("invalid durable install identity: %w", err)
}

func validateInstallID(id string) error {
	if len(id) != installIDBytes*2 || id != strings.ToLower(id) {
		return fmt.Errorf("want %d lowercase hexadecimal characters", installIDBytes*2)
	}
	decoded, err := hex.DecodeString(id)
	if err != nil || len(decoded) != installIDBytes {
		return fmt.Errorf("want %d lowercase hexadecimal characters", installIDBytes*2)
	}
	return nil
}

// installCohortID returns the updater's staged-rollout cohort key. It is never
// empty, so cohort bucketing never depends on ownership fail-closed semantics.
// A persisted value the pre-ownership reader accepted is used verbatim, keeping
// upgraded installs in the same cohort. Otherwise (unpersistable or unreadable
// file) the key is random for this run only, exactly as the old best-effort
// path behaved on a write failure; it is never written, so the ownership
// identity stays fail-closed until the file is repaired. Short or empty files
// are repaired by loadOrCreateInstallID, which installID calls first.
func installCohortID(dataDir string) string {
	if raw, err := os.ReadFile(filepath.Join(dataDir, "install-id")); err == nil {
		if id := strings.TrimSpace(string(raw)); len(id) >= legacyInstallIDMinLen {
			return id
		}
	}
	var buf [installIDBytes]byte
	// crypto/rand does not fail on shipped platforms; an all-zero key would
	// still be a usable cohort key.
	_, _ = rand.Read(buf[:])
	return hex.EncodeToString(buf[:])
}

// installID creates the durable identity when possible and returns the
// updater cohort key. Code which needs ownership semantics must use
// loadOrCreateInstallID and retain its error.
func installID(dataDir string) string {
	_, _ = loadOrCreateInstallID(dataDir)
	return installCohortID(dataDir)
}
